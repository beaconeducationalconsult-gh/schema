// Generates src/theme.css — dark-mode palette, "keep light" palette and projector tweaks.
//
//   node scripts/gen-theme-css.mjs
//
// Why generated: the app styles itself with Tailwind's raw palette (bg-slate-50,
// text-emerald-700, …). Rather than sprinkle `dark:` variants over ~60 files, dark
// mode re-maps the palette CSS variables under `.dark`. Utilities that hard-code a
// shade for *text* on a tinted background (text-blue-700 …) get explicit overrides
// because the same shade is also used for solid hover fills (bg-blue-700) that must
// NOT change.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const themeCss = readFileSync(join(dirname(require.resolve('tailwindcss/package.json')), 'theme.css'), 'utf8');

const HUES = ['emerald', 'blue', 'amber', 'rose', 'purple', 'cyan', 'sky'];
const orig = {};
for (const m of themeCss.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) orig[`${m[1]}-${m[2]}`] = m[3].trim();
const o = (hue, shade) => {
  const v = orig[`${hue}-${shade}`];
  if (!v) throw new Error(`missing ${hue}-${shade}`);
  return v;
};

/* ---- dark slate scale (hand-tuned; see README "Theming") ---- */
const SLATE_DARK = {
  50: '#0b1120', 100: '#1a2336', 200: '#27324a', 300: '#364359', 400: '#64748b',
  500: '#94a3b8', 600: '#cbd5e1', 700: '#e2e8f0', 800: '#f1f5f9', 900: '#f8fafc', 950: '#ffffff',
};
const TINT_MAP = { 50: 950, 100: 900, 200: 800, 300: 700 };      // light tints → deep tints
const TEXT_MAP = { 600: 400, 700: 300, 800: 200, 900: 100 };      // tinted text → readable on dark

const SURFACE_DARK = '#121b2f';

/* ---- which text-<hue>-<shade> utilities does the app actually use? ---- */
function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(jsx?|html)$/.test(f)) out.push(p);
  }
  return out;
}
const used = new Set();
const re = new RegExp(`(?<![\\w:/-])text-(${HUES.join('|')})-(600|700|800|900)(?![\\w-])`, 'g');
for (const file of [...walk(join(root, 'src')), join(root, 'index.html')]) {
  for (const m of readFileSync(file, 'utf8').matchAll(re)) used.add(`${m[1]}-${m[2]}`);
}
const textClasses = [...used].sort();

/* ---- emit ---- */
const L = [];
L.push('/* GENERATED by scripts/gen-theme-css.mjs — edit the script, not this file. */');
L.push('');
L.push('@custom-variant dark (&:where(.dark, .dark *));');
L.push('@custom-variant projector (&:where(.projector, .projector *));');
L.push('');

// Dark palette (screen only — printouts stay light)
L.push('@media screen {');
L.push('  .dark {');
L.push('    color-scheme: dark;');
L.push(`    --color-surface: ${SURFACE_DARK};`);
L.push('    --color-primary: #e2e8f0;');
L.push('    --color-primary-hover: #ffffff;');
L.push('    --color-on-primary: #0f172a;');
for (const [s, v] of Object.entries(SLATE_DARK)) L.push(`    --color-slate-${s}: ${v};`);
for (const h of HUES) for (const [from, to] of Object.entries(TINT_MAP)) L.push(`    --color-${h}-${from}: ${o(h, to)};`);
L.push('  }');
for (const c of textClasses) {
  const [h, s] = c.split('-');
  L.push(`  .dark .text-${c} { color: ${o(h, TEXT_MAP[s])}; }`);
}
L.push('');
L.push('  /* Inside .palette-fixed the light palette is restored, so undo the text overrides too. */');
for (const c of textClasses) {
  const [h, s] = c.split('-');
  L.push(`  .dark .palette-fixed .text-${c} { color: ${o(h, s)}; }`);
}
L.push('}');
L.push('');

// Always-dark surfaces (guided mode, toasts, status banner): restore the light-mode palette for the subtree.
L.push('/* Wrap a subtree in .palette-fixed to keep the original (light-mode) palette in dark mode. */');
L.push('.palette-fixed {');
L.push('  color-scheme: light;');
L.push('  --color-surface: #ffffff;');
L.push('  --color-primary: #0f172a;');
L.push('  --color-primary-hover: #1e293b;');
L.push('  --color-on-primary: #ffffff;');
for (const s of Object.keys(SLATE_DARK)) L.push(`  --color-slate-${s}: ${o('slate', s)};`);
for (const h of HUES) for (const s of Object.keys(TINT_MAP)) L.push(`  --color-${h}-${s}: ${o(h, s)};`);
L.push('}');
L.push('');

// Projector / classroom mode: bigger type + stronger secondary text.
L.push('/* Projector mode: larger base size (everything is rem-based) and higher-contrast secondary text. */');
L.push('html.projector { font-size: 125%; }');
L.push('.projector { --color-slate-400: #475569; --color-slate-500: #334155; --color-slate-600: #1e293b; }');
L.push('@media screen {');
L.push('  .dark.projector, .dark .projector { --color-slate-400: #cbd5e1; --color-slate-500: #e2e8f0; --color-slate-600: #f1f5f9; }');
L.push('}');
L.push('');

writeFileSync(join(root, 'src/theme.css'), L.join('\n'));
console.log(`wrote src/theme.css (${textClasses.length} text overrides: ${textClasses.join(', ')})`);
